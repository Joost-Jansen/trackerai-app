def test_sqlite_stays_the_default(tmp_path, monkeypatch):
    monkeypatch.setenv("DATA_DIR", str(tmp_path))
    monkeypatch.delenv(db.URL_VAR, raising=False)
    assert not db.on_postgres()
    conn = database.connect("anna")
    try:
        assert type(conn).__module__ == "sqlite3"
    finally:
        conn.close()


@pytest.fixture
def pg(tmp_path, monkeypatch):
    monkeypatch.setenv("DATA_DIR", str(tmp_path))
    monkeypatch.setenv(db.URL_VAR, PG_URL)
    folder = "t" + uuid.uuid4().hex[:12]
    conn = database.connect(folder)
    yield conn
    conn.rollback()
    conn.execute(f'DROP SCHEMA IF EXISTS "{db.schema_for(folder)}" CASCADE')
    conn.commit()
    conn.close()


@needs_pg
def test_postgres_connection_speaks_the_sqlite3_shape(pg):
    assert isinstance(pg, db.PgConnection)
    pg.executescript("CREATE TABLE t (id SERIAL PRIMARY KEY, isin TEXT UNIQUE, name TEXT, qty REAL);")
    cur = pg.execute("INSERT INTO t (isin, name, qty) VALUES (?, ?, ?)", ("NL001", "50% fund", 2.5))
    assert cur.rowcount == 1
    pg.executemany("INSERT INTO t (isin, name, qty) VALUES (?, ?, ?)", [("NL002", "b", 1), ("NL003", "c", 4)])
    assert pg.total_changes == 3 and pg.in_transaction
    pg.commit()
    assert not pg.in_transaction
    rows = pg.execute("SELECT isin, qty FROM t WHERE name LIKE '%fund' OR qty > ? ORDER BY isin", (3,)).fetchall()
    assert [(r["isin"], r[1]) for r in rows] == [("NL001", 2.5), ("NL003", 4)]
    cur = pg.execute("SELECT isin, name FROM t ORDER BY isin")
    assert [d[0] for d in cur.description] == ["isin", "name"]
    assert dict(zip(cur.fetchone().keys(), ("NL001", "50% fund"))) == {"isin": "NL001", "name": "50% fund"}
    assert pg.execute("SELECT count(*) FROM t").fetchone()[0] == 3


@needs_pg
def test_postgres_errors_are_caught_like_sqlite_ones(pg):
    pg.executescript("CREATE TABLE t (isin TEXT PRIMARY KEY);")
    pg.execute("INSERT INTO t VALUES (?)", ("NL001",))
    with pytest.raises(db.IntegrityError):
        pg.execute("INSERT INTO t VALUES (?)", ("NL001",))
    pg.rollback()


@needs_pg
def test_with_block_commits_or_rolls_back(pg):
    pg.executescript("CREATE TABLE t (isin TEXT PRIMARY KEY);")
    with pg:
        pg.execute("INSERT INTO t VALUES (?)", ("NL001",))
    with pytest.raises(RuntimeError):
        with pg:
            pg.execute("INSERT INTO t VALUES (?)", ("NL002",))
            raise RuntimeError("boom")
    assert [r[0] for r in pg.execute("SELECT isin FROM t").fetchall()] == ["NL001"]


@needs_pg
def test_each_user_gets_their_own_schema(tmp_path, monkeypatch):
    monkeypatch.setenv("DATA_DIR", str(tmp_path))
    monkeypatch.setenv(db.URL_VAR, PG_URL)
    a, b = ("t" + uuid.uuid4().hex[:12] for _ in range(2))
    ca, cb = database.connect(a), database.connect(b)
    try:
        ca.executescript("CREATE TABLE t (v TEXT);")
        cb.executescript("CREATE TABLE t (v TEXT);")
        ca.execute("INSERT INTO t VALUES (?)", ("mine",))
        ca.commit()
        assert cb.execute("SELECT count(*) FROM t").fetchone()[0] == 0
        assert os.path.isdir(os.path.join(tmp_path, "users", a, "uploads"))
    finally:
        for c, f in ((ca, a), (cb, b)):
            c.rollback()
            c.execute(f'DROP SCHEMA IF EXISTS "{db.schema_for(f)}" CASCADE')
            c.commit()
            c.close()



@needs_pg
def test_sqlite_only_sql_runs_on_postgres(pg):
    pg.executescript("""
        CREATE TABLE settings (key TEXT PRIMARY KEY, value TEXT);
        CREATE TABLE items (id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT UNIQUE, done INTEGER, at TEXT,
                            made TEXT DEFAULT CURRENT_TIMESTAMP);
    """)
    pg.execute("INSERT OR REPLACE INTO settings (key, value) VALUES (?, ?)", ("theme", "dark"))
    pg.execute("INSERT OR REPLACE INTO settings (key, value) VALUES (?, ?)", ("theme", "light"))
    pg.execute("INSERT OR IGNORE INTO settings (key, value) VALUES (?, ?)", ("theme", "ignored"))
    assert pg.execute("SELECT value FROM settings WHERE key = ?", ("theme",)).fetchone()[0] == "light"
    from datetime import date
    cur = pg.execute("INSERT INTO items (name, done, at) VALUES (?, ?, ?)", ("a", True, date(2026, 10, 9)))
    assert cur.lastrowid == 1
    row = pg.execute("SELECT * FROM items WHERE name LIKE 'A'").fetchone()
    assert row["done"] == 1 and row["at"] == "2026-10-09" and len(row["made"]) == 19
    cols = [r["name"] for r in pg.execute("PRAGMA table_info(items)").fetchall()]
    assert cols == ["id", "name", "done", "at", "made"]
    origins = {r["origin"] for r in pg.execute("PRAGMA index_list(items)").fetchall()}
    assert origins == {"pk", "u"}
    assert pg.execute("SELECT 1 FROM sqlite_master WHERE type = ? AND name = ?", ("table", "items")).fetchone()
    pg.execute("PRAGMA journal_mode = WAL")  # means nothing here, and does no harm
    pg.execute("BEGIN IMMEDIATE")
    assert round(pg.execute("SELECT ROUND(CAST(2.345 AS NUMERIC), 2)").fetchone()[0], 2) == 2.35
    assert pg.execute("SELECT SUM(done = 1), SUM(done = 2) FROM items").fetchone() == db.Row(("sum", "sum"), (1, 0))
    assert pg.execute("SELECT name FROM items WHERE at IS ?", (None,)).fetchall() == []
    assert pg.execute("SELECT MAX(at, '2027-01-01'), MIN(at, NULL) FROM items").fetchone()[:] == ("2027-01-01", None)
    with pytest.raises(db.IntegrityError):
        pg.execute("INSERT INTO items (name) VALUES (?)", ("a",))
    assert pg.execute("SELECT count(*) FROM items").fetchone()[0] == 1  # the transaction carries on, as in SQLite
