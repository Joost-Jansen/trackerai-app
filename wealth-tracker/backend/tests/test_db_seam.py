"""domain/db.py: the seam between the queries and SQLite or Postgres (step 11.7a).

The Postgres half runs when WEALTH_TEST_DATABASE_URL points at a database the test may make schemas in (CI starts
one); without it those tests are skipped.
"""

import os
import uuid

import pytest

from domain import database, db

PG_URL = os.environ.get("WEALTH_TEST_DATABASE_URL", "")
needs_pg = pytest.mark.skipif(not PG_URL, reason="WEALTH_TEST_DATABASE_URL not set")


@pytest.mark.parametrize("sql, has_params, expected", [
    ("SELECT * FROM t WHERE a = ? AND b = ?", True, "SELECT * FROM t WHERE a = %s AND b = %s"),
    ("SELECT '?' AS q, x FROM t WHERE y = ?", True, "SELECT '?' AS q, x FROM t WHERE y = %s"),
    ("SELECT * FROM t WHERE name LIKE '%a%' AND id = ?", True, "SELECT * FROM t WHERE name LIKE '%%a%%' AND id = %s"),
    ("SELECT * FROM t WHERE name LIKE '%a%'", False, "SELECT * FROM t WHERE name LIKE '%a%'"),
    ("SELECT 1 -- what? 50%\nWHERE x = ?", True, "SELECT 1 -- what? 50%%\nWHERE x = %s"),
    ('SELECT "odd?col" FROM t WHERE a = ?', True, 'SELECT "odd?col" FROM t WHERE a = %s'),
    ("SELECT 'it''s ?' WHERE a = ?", True, "SELECT 'it''s ?' WHERE a = %s"),
    ("INSERT INTO t VALUES (:isin, :date)", True, "INSERT INTO t VALUES (%(isin)s, %(date)s)"),
    ("SELECT ':not_a_param' WHERE x = :x", True, "SELECT ':not_a_param' WHERE x = %(x)s"),
])
def test_translate(sql, has_params, expected):
    assert db.translate(sql, has_params) == expected


@pytest.mark.parametrize("sql, expected", [
    ("CREATE TABLE t (id INTEGER PRIMARY KEY AUTOINCREMENT, b BLOB)",
     "CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, b BYTEA)"),
    ("CREATE TABLE t (id INTEGER PRIMARY KEY, x TEXT)", "CREATE TABLE t (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, x TEXT)"),
    ("CREATE TABLE t (amount REAL)", "CREATE TABLE t (amount DOUBLE PRECISION)"),
    ("CREATE TABLE b (account_id INTEGER NOT NULL REFERENCES accounts(id), t INTEGER REFERENCES x(id) ON DELETE CASCADE)",
     "CREATE TABLE b (account_id INTEGER NOT NULL, t INTEGER)"),
    ("SELECT * FROM t WHERE name LIKE ? AND note NOT LIKE '%LIKE%'", "SELECT * FROM t WHERE name ILIKE ? AND note NOT ILIKE '%LIKE%'"),
    ("SELECT 1 WHERE a IS ? AND b IS NOT ? AND c IS NULL AND d IS NOT NULL",
     "SELECT 1 WHERE a IS NOT DISTINCT FROM ? AND b IS DISTINCT FROM ? AND c IS NULL AND d IS NOT NULL"),
])
def test_dialect(sql, expected):
    assert db.dialect(sql) == expected


def test_row_reads_like_sqlite3_row():
    row = db.Row(("isin", "qty"), ("NL001", 3))
    assert row["isin"] == "NL001" and row[1] == 3 and list(row) == ["NL001", 3]
    assert dict(zip(row.keys(), row)) == {"isin": "NL001", "qty": 3}
    assert len(row) == 2
    with pytest.raises(IndexError):
        row["missing"]


