/** `base` with every key of `over` that is set; keeps Dutch for what has no translation yet. */
export function withFallback<X>(base: X, over: DeepPartial<X> | undefined): X {
  if (over === undefined) return base;
  if (typeof base !== "object" || base === null || typeof over !== "object" || over === null || Array.isArray(base)) return over as X;
  const out: Record<string, unknown> = { ...(base as Record<string, unknown>) };
  for (const [k, v] of Object.entries(over as Record<string, unknown>))
    out[k] = withFallback((base as Record<string, unknown>)[k], v as never);
  return out as X;
}

